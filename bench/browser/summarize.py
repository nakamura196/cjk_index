"""Summarizes results/<browser>.json into results/summary.md.

Usage (from the repository root): python3 bench/browser/summarize.py

Load times are medians over the runs. For queries, each run gives one time
per query (median of 5 trials of 10 searches); the table shows, for each
size, the median and the maximum over queries of the per-query median over
runs.
"""
import json
import statistics
from pathlib import Path

HERE = Path(__file__).resolve().parent
SIZES = {1000: "1.1", 5000: "5.6", 16951: "19.3"}


def med(xs):
    return statistics.median(xs)


lines = [
    "# Browser measurement (catalog-scale Aozora Bunko indexes)",
    "",
    "Generated by summarize.py from chrome.json and safari.json. Times in milliseconds;",
    "load = download (gzip on the wire, local server) + JSON.parse + Index construction.",
    "",
    "| browser | records | gzip MB | load | (download / parse / init) | query median | query max | JS heap MB | runs | mismatches |",
    "|---|---:|---:|---:|---|---:|---:|---:|---:|---:|",
]
agents = []
for browser in ("chrome", "safari"):
    rs = json.loads((HERE / "results" / f"{browser}.json").read_text())
    for n, gz in SIZES.items():
        runs = [r for r in rs if r["n"] == n]
        per_query = {q: med([r["times"][q] for r in runs]) for q in runs[0]["times"]}
        heap = [r["used_js_heap_bytes"] for r in runs if r["used_js_heap_bytes"]]
        lines.append(
            f"| {browser} | {n:,} | {gz} | {med([r['load_ms'] for r in runs]):.0f} "
            f"| {med([r['fetch_ms'] for r in runs]):.0f} / {med([r['parse_ms'] for r in runs]):.0f} / {med([r['init_ms'] for r in runs]):.0f} "
            f"| {med(per_query.values()):.2f} | {max(per_query.values()):.2f} "
            f"| {med(heap) / 1e6:.0f} | {len(runs)} | {sum(len(r['mismatch']) for r in runs)} |"
            if heap else
            f"| {browser} | {n:,} | {gz} | {med([r['load_ms'] for r in runs]):.0f} "
            f"| {med([r['fetch_ms'] for r in runs]):.0f} / {med([r['parse_ms'] for r in runs]):.0f} / {med([r['init_ms'] for r in runs]):.0f} "
            f"| {med(per_query.values()):.2f} | {max(per_query.values()):.2f} "
            f"| – | {len(runs)} | {sum(len(r['mismatch']) for r in runs)} |"
        )
    agents.append(f"- {browser}: `{rs[0]['userAgent']}`")
lines += ["", "User agents:", ""] + agents

(HERE / "results" / "summary.md").write_text("\n".join(lines) + "\n")
print("\n".join(lines))
