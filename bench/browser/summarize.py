"""Summarizes results/<browser>.json and <browser>-split.json into results/summary.md.

Usage (from the repository root): python3 bench/browser/summarize.py

Load times are medians over the runs. For queries, each run gives one time
per query (median of 5 trials of 10 searches); the tables show, for each
size, the median and the maximum over queries of the per-query median over
runs. For the split index, the first search of each query (fetching its
shards, from a fresh Index on the manifest) is summarized the same way, and
so are the bytes (gzip) and requests it fetched.
"""
import json
import statistics
from pathlib import Path

HERE = Path(__file__).resolve().parent
BROWSERS = ("chrome", "safari")


def med(xs):
    return statistics.median(xs)


def per_query(runs, key):
    return {q: med([r[key][q] for r in runs]) for q in runs[0][key]}


def load(name):
    path = HERE / "results" / f"{name}.json"
    return json.loads(path.read_text()) if path.exists() else None


def heap(runs):
    h = [r["used_js_heap_bytes"] for r in runs if r["used_js_heap_bytes"]]
    return f"{med(h) / 1e6:.0f}" if h else "–"


def sizes(rs):
    return sorted({r["n"] for r in rs})


lines = [
    "# Browser measurement (catalog-scale Aozora Bunko indexes)",
    "",
    "Generated by summarize.py from results/<browser>.json and <browser>-split.json.",
    "Times in milliseconds; sizes are what was sent (gzip). load = download (gzip on",
    "the wire, local server) + JSON.parse + Index construction.",
    "",
    "## One index file",
    "",
    "| browser | records | gzip MB | load | (download / parse / init) | query median | query max | JS heap MB | runs | mismatches |",
    "|---|---:|---:|---:|---|---:|---:|---:|---:|---:|",
]
agents = []
for browser in BROWSERS:
    rs = load(browser)
    if not rs:
        continue
    for n in sizes(rs):
        runs = [r for r in rs if r["n"] == n]
        q = per_query(runs, "times")
        lines.append(
            f"| {browser} | {n:,} | {runs[0]['load_bytes'] / 1e6:.1f} | {med([r['load_ms'] for r in runs]):.0f} "
            f"| {med([r['fetch_ms'] for r in runs]):.0f} / {med([r['parse_ms'] for r in runs]):.0f} / {med([r['init_ms'] for r in runs]):.0f} "
            f"| {med(q.values()):.2f} | {max(q.values()):.2f} "
            f"| {heap(runs)} | {len(runs)} | {sum(len(r['mismatch']) for r in runs)} |"
        )
    agents.append(f"- {browser}: `{rs[0]['userAgent']}`")

lines += [
    "",
    "## Split index",
    "",
    "load is the manifest only. first search = searchAsync on a fresh Index, fetching",
    "the shards the query needs; then searches as above.",
    "",
    "| browser | records | manifest KB | load | first search median / max | fetched KB median / max | requests median / max | query median | query max | JS heap MB | runs | mismatches |",
    "|---|---:|---:|---:|---|---|---|---:|---:|---:|---:|---:|",
]
for browser in BROWSERS:
    rs = load(f"{browser}-split")
    if not rs:
        continue
    for n in sizes(rs):
        runs = [r for r in rs if r["n"] == n]
        q = per_query(runs, "times")
        cold = per_query(runs, "cold_ms")
        kb = {k: v / 1e3 for k, v in runs[0]["cold_bytes"].items()}
        req = runs[0]["cold_requests"]
        lines.append(
            f"| {browser} | {n:,} | {runs[0]['load_bytes'] / 1e3:.0f} | {med([r['load_ms'] for r in runs]):.0f} "
            f"| {med(cold.values()):.1f} / {max(cold.values()):.1f} "
            f"| {med(kb.values()):.0f} / {max(kb.values()):.0f} "
            f"| {med(req.values()):.0f} / {max(req.values())} "
            f"| {med(q.values()):.2f} | {max(q.values()):.2f} "
            f"| {heap(runs)} | {len(runs)} | {sum(len(r['mismatch']) for r in runs)} |"
        )

lines += ["", "User agents:", ""] + agents

(HERE / "results" / "summary.md").write_text("\n".join(lines) + "\n")
print("\n".join(lines))
