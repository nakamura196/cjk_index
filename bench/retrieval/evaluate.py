"""Scores every results/<corpus>-<engine>.tsv against qrels/ and writes results/summary.md.

    python3 -I bench/retrieval/evaluate.py

Set-based: a returned record is a true positive when it is judged relevant.
A returned record that is not in the pool is counted as a false positive
(it contains none of the hand-listed spellings) and listed as "unjudged".
"""
import collections
import csv
import glob
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ENGINES = ["cjk_index", "lunr-default", "lunr-ja-or", "lunr-ja-and"]


def read_tsv(path):
    with open(path, encoding="utf-8") as f:
        return list(csv.DictReader(f, delimiter="\t", quoting=csv.QUOTE_NONE))


def main():
    queries = read_tsv(os.path.join(HERE, "queries.tsv"))
    judged = {}  # (qid, doc) -> rel
    for path in glob.glob(os.path.join(HERE, "qrels", "*.tsv")):
        for row in read_tsv(path):
            judged[(row["qid"], row["doc"])] = int(row["rel"])
    relevant = collections.defaultdict(set)
    for (qid, doc), rel in judged.items():
        if rel:
            relevant[qid].add(doc)

    out = ["# Retrieval results", "", "Generated by evaluate.py. P = precision, R = recall over the queries listed.", ""]
    detail = ["## Per query", ""]
    for corpus in ["utokyo", "aozora"]:
        qs = [q for q in queries if q["corpus"] == corpus]
        runs = {}
        for engine in ENGINES:
            path = os.path.join(HERE, "results", f"{corpus}-{engine}.tsv")
            hits = collections.defaultdict(list)
            for row in read_tsv(path):
                hits[row["qid"]].append(row["doc"])
            runs[engine] = hits
        out += [f"## {corpus}", "", "| engine | category | queries | TP | FP | FN | P | R |", "|---|---|---:|---:|---:|---:|---:|---:|"]
        groups = [("all", qs)] + [(c, [q for q in qs if q["category"] == c]) for c in dict.fromkeys(q["category"] for q in qs)]
        for engine in ENGINES:
            for name, group in groups:
                tp = fp = fn = 0
                for q in group:
                    got = set(runs[engine][q["qid"]])
                    tp += len(got & relevant[q["qid"]])
                    fp += len(got - relevant[q["qid"]])
                    fn += len(relevant[q["qid"]] - got)
                p = f"{tp / (tp + fp):.3f}" if tp + fp else "–"
                r = f"{tp / (tp + fn):.3f}" if tp + fn else "–"
                out.append(f"| {engine} | {name} | {len(group)} | {tp} | {fp} | {fn} | {p} | {r} |")
        out.append("")
        detail += [f"### {corpus}", "", "| qid | query | category | relevant | " + " | ".join(f"{e} hits / TP / FP" for e in ENGINES) + " |",
                   "|---|---|---|---:|" + "---:|" * len(ENGINES)]
        misses = []
        for q in qs:
            rel = relevant[q["qid"]]
            cells = []
            for engine in ENGINES:
                got = runs[engine][q["qid"]]
                s = set(got)
                cells.append(f"{len(got)} / {len(s & rel)} / {len(s - rel)}")
                for doc in sorted(s - rel) if engine == "cjk_index" else []:
                    kind = "judged 0" if (q["qid"], doc) in judged else "unjudged"
                    misses.append(f"- {engine} {q['qid']} {q['query']}: false positive {doc} ({kind})")
                for doc in sorted(rel - s):
                    if engine == "cjk_index":
                        misses.append(f"- {engine} {q['qid']} {q['query']}: missed {doc}")
            detail.append(f"| {q['qid']} | {q['query']} | {q['category']} | {len(rel)} | " + " | ".join(cells) + " |")
        detail += ["", "False positives and misses of cjk_index (the lunr runs are in results/*.tsv):", ""] + (misses or ["- none"]) + [""]
    with open(os.path.join(HERE, "results", "summary.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(out + detail))
    print("\n".join(out))


main()
